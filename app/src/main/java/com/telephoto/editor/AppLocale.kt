    private const val PREFS_NAME = "telephoto_app_prefs"
    private const val KEY_LANG = "app_language"

    @Volatile
    var currentCode: String = "en"
        private set

    fun init(context: Context) {
        val saved = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
            .getString(KEY_LANG, "en") ?: "en"
        currentCode = if (SUPPORTED_LANGUAGES.any { it.code == saved }) saved else "en"
    }

    fun setLanguage(context: Context, code: String) {
        val valid = if (SUPPORTED_LANGUAGES.any { it.code == code }) code else "en"
        currentCode = valid
        context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
            .edit().putString(KEY_LANG, valid).apply()
    }

    fun currentLanguage(): LanguageOption =
        SUPPORTED_LANGUAGES.firstOrNull { it.code == currentCode } ?: SUPPORTED_LANGUAGES[0]

    fun isRtl(): Boolean = currentLanguage().isRtl

    fun layoutDirection(): Int = if (isRtl()) View.LAYOUT_DIRECTION_RTL else View.LAYOUT_DIRECTION_LTR

    fun t(key: String): String {
        val table = translations[currentCode]
        return table?.get(key) ?: english[key] ?: key
    }

